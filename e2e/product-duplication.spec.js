// Couvre un bug découvert pendant la Phase 1.3 : dupliquer un produit chargé depuis un fichier
// (donc sans l'ancien champ "labor") faisait planter l'application (référence à un champ
// renommé depuis en "productionSteps"). Corrigé dans App.jsx (handleDuplicateProduct).
import { test, expect } from '@playwright/test';

test('dupliquer un produit du projet démo ne plante pas et crée une copie', async ({ page }) => {
    const errors = [];
    page.on('pageerror', (err) => errors.push(err.message));
    page.on('console', (msg) => { if (msg.type() === 'error') errors.push(msg.text()); });

    await page.goto('/');
    await page.getByText('Explorer un projet démo').click();

    // Vue maître-détail (refonte du 19/10) : sélectionne le premier produit de la liste de
    // gauche, son détail s'affiche à droite.
    const menuSection = page.locator('#tutorial-section-info-menu');
    await menuSection.locator('[id^="product-list-item-"]').first().click();
    const detailPane = menuSection.locator('#product-detail-pane');
    const firstRowName = await detailPane.locator('input[type="text"]').first().inputValue();

    await detailPane.locator('button[title="Dupliquer le plat"]').click();
    await page.waitForTimeout(300);

    // Le duplicata est sélectionné automatiquement : son détail s'affiche directement dans le
    // panneau de droite.
    await expect(detailPane.locator('input[type="text"]').first()).toHaveValue(`${firstRowName} (Copie)`);
    expect(errors, `Erreurs console/page inattendues :\n${errors.join('\n')}`).toEqual([]);
});

// Régression (04/10) : le SKU d'un format dupliqué (produit ou format) ne se régénérait plus
// jamais après coup — handleDuplicateProduct/handleDuplicateFormat suffixaient "-copie" au SKU de
// l'ORIGINAL sans jamais le reconstruire sur le nouveau nom, ce qui cassait la détection "SKU
// encore auto-généré" (isAutoGeneratedSku, App.jsx) dès la duplication. Corrigé en régénérant
// immédiatement un SKU propre à la duplication quand l'original était encore auto.
test('le SKU d\'un produit dupliqué se régénère au renommage de la copie', async ({ page }) => {
    await page.goto('/');
    await page.getByText('Explorer un projet démo').click();
    await page.waitForTimeout(500);
    await page.locator('button:has-text("Paramètres")').click();
    const menuSection = page.locator('#tutorial-section-info-menu');
    await menuSection.scrollIntoViewIfNeeded();
    for (const s of await page.locator('select').all()) {
        if ((await s.locator('option').allTextContents()).includes('100')) { await s.selectOption('100'); break; }
    }
    await page.waitForTimeout(300);

    // Vue maître-détail (refonte du 19/10) : sélectionne le produit dans la liste de gauche.
    await menuSection.getByText('Saumon teriyaki, riz et légumes', { exact: true }).click();
    const detailPane = menuSection.locator('#product-detail-pane');
    await detailPane.locator('button[title="Dupliquer le plat"]').click();
    await page.waitForTimeout(300);

    // Le duplicata est sélectionné automatiquement (plus besoin de le retrouver dans la liste par
    // un id généré, voir handleDuplicateProduct — simplification directe de la vue maître-détail).
    await expect(detailPane.locator('input[type="text"]').first()).toHaveValue('Saumon teriyaki, riz et légumes (Copie)');
    const skuInput = detailPane.locator('tbody tr').first().locator('input[type="text"]').nth(1);

    await detailPane.locator('input[type="text"]').first().fill('Thon teriyaki, riz et légumes');
    await page.waitForTimeout(300);
    await expect(skuInput).not.toHaveValue(/copie/i);
    await expect(skuInput).toHaveValue(/thon/i);
});

test('le SKU d\'un format dupliqué se régénère proprement si on en change la quantité', async ({ page }) => {
    await page.goto('/');
    await page.getByText('Explorer un projet démo').click();
    await page.waitForTimeout(500);
    await page.locator('button:has-text("Paramètres")').click();
    const menuSection = page.locator('#tutorial-section-info-menu');
    await menuSection.scrollIntoViewIfNeeded();
    for (const s of await page.locator('select').all()) {
        if ((await s.locator('option').allTextContents()).includes('100')) { await s.selectOption('100'); break; }
    }
    await page.waitForTimeout(300);

    // Vue maître-détail (refonte du 19/10) : sélectionne le produit dans la liste de gauche.
    await menuSection.getByText('Saumon teriyaki, riz et légumes', { exact: true }).click();
    const target = menuSection.locator('#product-detail-pane');
    await target.locator('button[title="Dupliquer ce format"]').click();
    await page.waitForTimeout(300);

    const newFormatRow = target.locator('tbody tr').nth(1);
    const skuInput = newFormatRow.locator('input[type="text"]').nth(1);
    await expect(skuInput).toHaveValue(/copie/i); // suffixé tant que la quantité est identique à l'original

    await newFormatRow.locator('input[inputmode="decimal"]').first().fill('500');
    await page.waitForTimeout(300);
    await expect(skuInput).not.toHaveValue(/copie/i);
    await expect(skuInput).toHaveValue(/500/);
});
